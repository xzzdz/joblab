/**
 * ค่าที่มาจาก dynamic segment ของ URL (เช่น `[slug]`) ยังเป็นแบบ percent-encoded อยู่
 *
 * ตัวอย่างจริงที่เจอใน Phase 3:
 *   URL   /jobs/%E0%B8%99%E0%B8%B1%E0%B8%81...
 *   params.slug ที่ page ได้รับ = "%E0%B8%99%E0%B8%B1%E0%B8%81..."   ← ยังไม่ถูกแปลง
 *   ค่าที่อยู่ใน DB จริง        = "นักพัฒนาเว็บไซต์-อาวุโส"
 * เอาไปค้นตรง ๆ จึงไม่เจอ แล้วหน้าเว็บตอบ 404 ทั้งที่ข้อมูลมีอยู่
 *
 * slug ที่เป็นภาษาอังกฤษล้วนไม่มีปัญหา เพราะไม่มีอะไรให้เข้ารหัส — บั๊กแบบนี้จึง
 * ไม่โผล่จนกว่าจะมีข้อมูลภาษาไทยเข้ามา
 *
 * หมายเหตุ: Route Handler (`route.ts`) ได้ค่าที่ decode มาแล้ว ต่างจาก Page
 * เพราะฉะนั้นอย่าเหมาว่าทั้งสองที่ทำงานเหมือนกัน
 */
export function decodeRouteParam(raw: string): string {
  try {
    return decodeURIComponent(raw);
  } catch {
    // ถ้าเจอ %xx ที่ผิดรูป (เช่น "%zz") decodeURIComponent จะโยน URIError
    // คืนค่าเดิมไปแทนที่จะให้หน้าพัง — ค้นไม่เจอแล้วตอบ 404 ตามปกติ
    return raw;
  }
}
